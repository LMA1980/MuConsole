#!/usr/bin/env bash
# scripts/build-dist.sh: Compile MuConsole UI + Data Worker WASM release bundle and package into dist/
set -euo pipefail

cd "$(dirname "$0")/.."

if [ ! -f dist/fonts/HurmitNerdFontMono-Regular.woff2 ]; then
    echo "Font subsets not found in dist/fonts/; running scripts/fetch-fonts.sh..."
    ./scripts/fetch-fonts.sh
fi

echo "Building muconsole-ui and muconsole-data release WASM binaries..."
cargo build --target wasm32-unknown-unknown --release -p muconsole-ui -p muconsole-data

echo "Packaging muconsole-ui (main thread) and muconsole-data (worker) with wasm-bindgen..."
mkdir -p dist
wasm-bindgen --target web --out-dir dist --out-name muconsole-ui \
    target/wasm32-unknown-unknown/release/muconsole-ui.wasm
wasm-bindgen --target no-modules --out-dir dist --out-name muconsole-data \
    target/wasm32-unknown-unknown/release/muconsole-data.wasm

cp crates/muconsole-theme/assets/tokens.css dist/tokens.css

hash_file() {
    if command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$@" | shasum -a 256 | cut -c1-10
    elif command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$@" | sha256sum | cut -c1-10
    else
        date +%s
    fi
}

UI_HASH=$(hash_file dist/muconsole-ui_bg.wasm dist/muconsole-ui.js)
DATA_HASH=$(hash_file dist/muconsole-data_bg.wasm dist/muconsole-data.js)
CSS_HASH=$(hash_file dist/tokens.css)
FONT_HASH=$(hash_file dist/fonts/manifest.txt)

echo "Writing dist/muconsole-data_loader.js (?v=${DATA_HASH})..."
cat > dist/muconsole-data_loader.js <<EOF
// Generated by scripts/build-dist.sh — Dedicated Web Worker loader shim
const __muconsolePending = [];
self.onmessage = (ev) => __muconsolePending.push(ev);
importScripts("/muconsole-data.js?v=${DATA_HASH}");
wasm_bindgen("/muconsole-data_bg.wasm?v=${DATA_HASH}").then(() => {
  for (const ev of __muconsolePending.splice(0)) {
    if (typeof self.onmessage === "function") {
      self.onmessage(ev);
    }
  }
}).catch((err) => {
  console.error("muconsole-data worker initialization failed:", err);
});
EOF

echo "Injecting cache-busting versions (ui=${UI_HASH}, data=${DATA_HASH}, css=${CSS_HASH}, fonts=${FONT_HASH}) into dist/index.html..."
sed -e "s|href=\"/tokens\.css\"|href=\"/tokens.css?v=${CSS_HASH}\"|g" \
    -e "s|url(\"/fonts/\([^\"]*\)\.woff2\")|url(\"/fonts/\1.woff2?v=${FONT_HASH}\")|g" \
    -e "s|from '/muconsole-ui\.js'|from '/muconsole-ui.js?v=${UI_HASH}'|g" \
    -e "s|init('/muconsole-ui_bg\.wasm')|init('/muconsole-ui_bg.wasm?v=${UI_HASH}')|g" \
    index.html > dist/index.html

echo "Build complete: dist/ is ready for Nginx deployment."
ls -lh dist/ dist/fonts/
